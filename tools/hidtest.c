// kernel/drivers/hid.c, checked on the build machine against three real mouse
// report descriptors -- among them the Logitech gaming-receiver layout, which
// QEMU has no device for. From the top of the project:
//
//     gcc -Wall -O2 -o /tmp/hidtest tools/hidtest.c && /tmp/hidtest
#include <stdio.h>
#include "../kernel/drivers/hid.c"

static int bad;

static void show(const char *name, const uint8_t *d, int n, const uint8_t *rep, int rn,
                 int eb, int ex, int ey, int ew) {
    hid_mouse_fmt f;
    int ok = hid_parse_mouse(d, n, &f);
    int b, x, y, w;
    int r = hid_mouse_read(&f, rep, rn, &b, &x, &y, &w);
    int pass = ok && r && b == eb && x == ex && y == ey && w == ew;
    printf("%-10s parsed=%d id=%d btn=%d,%d,%d x=%d/%d y=%d/%d w=%d/%d -> b=%d x=%d y=%d w=%d  %s\n",
           name, ok, f.id, f.btn[0], f.btn[1], f.btn[2], f.x, f.xs, f.y, f.ys,
           f.wheel, f.ws, b, x, y, w, pass ? "ok" : "FAIL");
    if (!pass) bad++;
}

int main(void) {
    // Logitech gaming receiver, interface 0: 16 buttons, X/Y 16-bit, wheel, AC pan.
    // Read as a boot report, left-right motion comes out as up-down.
    static const uint8_t lg[] = {
        0x05,0x01,0x09,0x02,0xa1,0x01,0x09,0x01,0xa1,0x00,0x05,0x09,0x19,0x01,0x29,0x10,
        0x15,0x00,0x25,0x01,0x95,0x10,0x75,0x01,0x81,0x02,0x05,0x01,0x16,0x01,0x80,0x26,
        0xff,0x7f,0x75,0x10,0x95,0x02,0x09,0x30,0x09,0x31,0x81,0x06,0x15,0x81,0x25,0x7f,
        0x75,0x08,0x95,0x01,0x09,0x38,0x81,0x06,0x05,0x0c,0x0a,0x38,0x02,0x95,0x01,0x81,
        0x06,0xc0,0xc0 };
    static const uint8_t lg_rep[] = { 0x01, 0x00, 0x05, 0x00, 0xFD, 0xFF, 0x01, 0x00 };
    show("lightspeed", lg, sizeof lg, lg_rep, sizeof lg_rep, 1, 5, -3, 1);

    // QEMU usb-mouse.
    static const uint8_t qm[] = {
        0x05,0x01,0x09,0x02,0xa1,0x01,0x09,0x01,0xa1,0x00,0x05,0x09,0x19,0x01,0x29,0x05,
        0x15,0x00,0x25,0x01,0x95,0x05,0x75,0x01,0x81,0x02,0x95,0x01,0x75,0x03,0x81,0x01,
        0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,0x15,0x81,0x25,0x7f,0x75,0x08,0x95,0x03,
        0x81,0x06,0x05,0x0c,0x0a,0x38,0x02,0x15,0x81,0x25,0x7f,0x75,0x08,0x95,0x01,0x81,
        0x06,0xc0,0xc0 };
    static const uint8_t qm_rep[] = { 0x02, 0x10, 0xF0, 0xFF };
    show("qemu", qm, sizeof qm, qm_rep, sizeof qm_rep, 2, 16, -16, -1);

    // A report-ID mouse with 12-bit X/Y (the Unifying/DJ layout).
    static const uint8_t dj[] = {
        0x05,0x01,0x09,0x02,0xa1,0x01,0x85,0x02,0x09,0x01,0xa1,0x00,0x05,0x09,0x19,0x01,
        0x29,0x10,0x15,0x00,0x25,0x01,0x95,0x10,0x75,0x01,0x81,0x02,0x05,0x01,0x16,0x01,
        0xf8,0x26,0xff,0x07,0x75,0x0c,0x95,0x02,0x09,0x30,0x09,0x31,0x81,0x06,0x15,0x81,
        0x25,0x7f,0x75,0x08,0x95,0x01,0x09,0x38,0x81,0x06,0x05,0x0c,0x0a,0x38,0x02,0x95,
        0x01,0x81,0x06,0xc0,0xc0 };
    // id 2, buttons=0x0004, x=-2 (0xFFE), y=+7 (0x007): bytes 16..39 = FE 7F 00
    static const uint8_t dj_rep[] = { 0x02, 0x04, 0x00, 0xFE, 0x7F, 0x00, 0xFF, 0x00 };
    show("unifying", dj, sizeof dj, dj_rep, sizeof dj_rep, 4, -2, 7, -1);

    // A report with another ID must be refused.
    hid_mouse_fmt f; int b, x, y, w;
    hid_parse_mouse(dj, sizeof dj, &f);
    static const uint8_t other[] = { 0x03, 0x01, 0x02 };
    int r = hid_mouse_read(&f, other, sizeof other, &b, &x, &y, &w);
    printf("other id   read=%d  %s\n", r, r == 0 ? "ok" : "FAIL");
    if (r) bad++;

    printf(bad ? "%d FAILED\n" : "all good\n", bad);
    return bad;
}
